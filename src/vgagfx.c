/* ── Drawing functions ────────────────────────────────── */
void gfx_set_pixel(uint16_t x, uint16_t y, uint8_t color) {
    if (x < GFX_WIDTH && y < GFX_HEIGHT)
        GFX_FB[y * GFX_WIDTH + x] = color;
}

void gfx_clear(uint8_t color) {
    for (uint32_t i = 0; i < GFX_WIDTH * GFX_HEIGHT; i++)
        GFX_FB[i] = color;
}

void gfx_fill_rect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint8_t color) {
    for (uint16_t dy = 0; dy < h; dy++)
        for (uint16_t dx = 0; dx < w; dx++)
            gfx_set_pixel(x + dx, y + dy, color);
}

void gfx_draw_rect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint8_t color) {
    for (uint16_t dx = 0; dx < w; dx++) {
        gfx_set_pixel(x + dx, y, color);
        gfx_set_pixel(x + dx, y + h - 1, color);
    }
    for (uint16_t dy = 0; dy < h; dy++) {
        gfx_set_pixel(x, y + dy, color);
        gfx_set_pixel(x + w - 1, y + dy, color);
    }
}

void gfx_draw_line(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2, uint8_t color) {
    int dx = (int)x2 - (int)x1; if (dx < 0) dx = -dx;
    int dy = (int)y2 - (int)y1; if (dy < 0) dy = -dy;
    int sx = x1 < x2 ? 1 : -1;
    int sy = y1 < y2 ? 1 : -1;
    int err = dx - dy;
    int x = x1, y = y1;
    while (1) {
        gfx_set_pixel(x, y, color);
        if (x == x2 && y == y2) break;
        int e2 = err * 2;
        if (e2 > -dy) { err -= dy; x += sx; }
        if (e2 < dx)  { err += dx; y += sy; }
    }
}

void gfx_draw_char(uint16_t x, uint16_t y, char c, uint8_t fg, uint8_t bg) {
    if (c < 32 || c > 126) return;
    const uint8_t* glyph = font_8x8[c - 32];
    for (int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            gfx_set_pixel(x + col, y + row, (bits & 0x80) ? fg : bg);
            bits <<= 1;
        }
    }
}

void gfx_draw_text(uint16_t x, uint16_t y, const char* str, uint8_t fg, uint8_t bg) {
    while (*str) { gfx_draw_char(x, y, *str++, fg, bg); x += 8; }
}

/* ═══════════════════════════════════════════════════════
   Mode switching — hardcoded register sets
   (more reliable than save/restore which is fragile)
   ═══════════════════════════════════════════════════════ */

static void write_regs(uint16_t port, uint8_t* vals, int count) {
    for (int i = 0; i < count; i++) {
        outb(port, (uint8_t)i);
        outb(port + 1, vals[i]);
    }
}

/* Standard VGA mode 3 (80x25 text) register set.
   Tested working on QEMU and real hardware. */
static void set_text_mode(void) {
    /* Disable display */
    inb(0x3DA); outb(0x3C0, 0x00);

    /* Misc */
    outb(0x3C2, 0x67);

    /* Sequencer */
    { uint8_t v[] = {0x03,0x00,0x03,0x00,0x02}; write_regs(0x3C4, v, 5); }

    /* CRTC — unlock first */
    outb(0x3D4, 0x11); outb(0x3D5, 0x00);
    { uint8_t v[] = {
        0x5F,0x4F,0x50,0x82,0x55,0x81,0xBF,0x1F,
        0x00,0x4F,0x0D,0x0E,0x00,0x00,0x00,0x50,
        0x9C,0x0E,0x8F,0x28,0x1F,0x96,0xB9,0xA3,0xFF
    }; write_regs(0x3D4, v, 25); }

    /* Graphics controller */
    { uint8_t v[] = {0x00,0x00,0x00,0x00,0x00,0x10,0x0E,0x0F,0xFF}; write_regs(0x3CE, v, 9); }

    /* Attribute controller — palette + mode */
    inb(0x3DA);
    { uint8_t v[] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,
        0x08,0x09,0x0A,0x0B,0x0C,0x0D,0x0E,0x0F
    };
    for (int i = 0; i < 16; i++) {
        outb(0x3C0, (uint8_t)i); outb(0x3C0, v[i]);
    }}
    /* Mode control: enable text (bit3=0), enable blink, palette width=6bit */
    outb(0x3C0, 0x10); outb(0x3C0, 0x0C);
    /* Overscan color = black */
    outb(0x3C0, 0x11); outb(0x3C0, 0x00);
    /* Color plane enable */
    outb(0x3C0, 0x12); outb(0x3C0, 0x0F);
    /* Horizontal PEL panning */
    outb(0x3C0, 0x13); outb(0x3C0, 0x08);
    /* Color select */
    outb(0x3C0, 0x14); outb(0x3C0, 0x00);

    /* Re-enable display */
    inb(0x3DA); outb(0x3C0, 0x20);

    /* Select font: use character map A */
    outb(0x3C4, 0x03); outb(0x3C5, 0x00);

    /* Clear video memory */
    volatile uint16_t* vmem = (uint16_t*)0xB8000;
    for (int i = 0; i < 80*25; i++) vmem[i] = 0x0720;

    /* Home cursor */
    outb(0x3D4, 0x0E); outb(0x3D5, 0x00);
    outb(0x3D4, 0x0F); outb(0x3D5, 0x00);
}

/* Standard VGA mode 13h (320x200x256) register set */
static void set_gfx_mode(void) {
    inb(0x3DA); outb(0x3C0, 0x00);

    outb(0x3C2, 0x63);

    { uint8_t v[] = {0x03,0x01,0x0F,0x00,0x0E}; write_regs(0x3C4, v, 5); }

    outb(0x3D4, 0x11); outb(0x3D5, 0x00);
    { uint8_t v[] = {
        0x5F,0x4F,0x50,0x82,0x54,0x80,0xBF,0x1F,
        0x00,0x41,0x00,0x00,0x00,0x00,0x00,0x00,
        0x9C,0x0E,0x8F,0x28,0x40,0x96,0xB9,0xA3,0xFF
    }; write_regs(0x3D4, v, 25); }

    { uint8_t v[] = {0x00,0x00,0x00,0x00,0x00,0x40,0x05,0x0F,0xFF}; write_regs(0x3CE, v, 9); }

    inb(0x3DA);
    for (int i = 0; i < 16; i++) { outb(0x3C0, (uint8_t)i); outb(0x3C0, (uint8_t)i); }
    outb(0x3C0, 0x10); outb(0x3C0, 0x41); /* Graphics mode */
    outb(0x3C0, 0x11); outb(0x3C0, 0x00);
    outb(0x3C0, 0x12); outb(0x3C0, 0x0F);
    outb(0x3C0, 0x13); outb(0x3C0, 0x00);
    outb(0x3C0, 0x14); outb(0x3C0, 0x00);

    inb(0x3DA); outb(0x3C0, 0x20);
}

/* ── Public ───────────────────────────────────────────── */
void gfx_switch_to(void)  { set_gfx_mode(); }
void gfx_switch_back(void) { set_text_mode(); }
void gfx_init(void)       { set_gfx_mode(); gfx_clear(0); }
